val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) {
        FileInputStream(keystorePropsFile).use { load(it) }
    }
}

val releaseStoreFilePath: String? =
    keystoreProps.getProperty("storeFile") ?: System.getenv("SCROLLGUARD_KEYSTORE_PATH")
val releaseStorePassword: String? =
    keystoreProps.getProperty("storePassword") ?: System.getenv("SCROLLGUARD_KEYSTORE_PASSWORD")
val releaseKeyAlias: String? =
    keystoreProps.getProperty("keyAlias") ?: System.getenv("SCROLLGUARD_KEY_ALIAS")
val releaseKeyPassword: String? =
    keystoreProps.getProperty("keyPassword") ?: System.getenv("SCROLLGUARD_KEY_PASSWORD")

val hasReleaseSigning = !releaseStoreFilePath.isNullOrBlank() &&
    !releaseStorePassword.isNullOrBlank() &&
    !releaseKeyAlias.isNullOrBlank() &&
    !releaseKeyPassword.isNullOrBlank() &&
    rootProject.file(releaseStoreFilePath).exists()

